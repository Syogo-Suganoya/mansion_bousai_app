-- 地域危険度データ（町丁目単位）
-- ※ シードデータはデモ用サンプル。本番では東京都都市整備局
--   「地震に関する地域危険度測定調査」CSV と下水道局「浸水予想区域図」を投入して差し替える。
CREATE TABLE risk_areas (
  id SERIAL PRIMARY KEY,
  muni_cd TEXT NOT NULL,          -- 市区町村コード（例: 13104 = 新宿区）
  ward TEXT NOT NULL,             -- 区名
  town_name TEXT NOT NULL,        -- 町丁目名（国土地理院逆ジオコーダの lv01Nm 形式）
  collapse_rank INT NOT NULL,     -- 建物倒壊危険度 1-5
  fire_rank INT NOT NULL,         -- 火災危険度 1-5
  total_rank INT NOT NULL,        -- 総合危険度 1-5
  flood_depth_m NUMERIC NOT NULL DEFAULT 0,  -- 想定最大浸水深(m) 0=浸水想定なし
  UNIQUE (muni_cd, town_name)
);

CREATE INDEX idx_risk_areas_lookup ON risk_areas (muni_cd, town_name);

-- 目安箱投稿（避難所ニーズ / 住民の余剰備蓄）
CREATE TABLE posts (
  id SERIAL PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('shelter', 'resident')),  -- 投稿者: 避難所 / マンション住民
  kind TEXT NOT NULL CHECK (kind IN ('need', 'offer')),        -- 不足 / 余剰提供
  category TEXT NOT NULL,        -- 物資カテゴリタグ
  quantity INT NOT NULL DEFAULT 1,
  ward TEXT NOT NULL,            -- 地域（区）
  place TEXT,                    -- 避難所名・マンション名など任意
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_posts_match ON posts (ward, category, kind);

